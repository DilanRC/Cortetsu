#!/usr/bin/env python3
"""Regenerate src/keycodes.rs from linux/input-event-codes.h.

The table is committed so a build never depends on the headers installed on
the machine. Only KEY_* and BTN_* codes with a numeric value are kept; for a
code with several names (KEY_HANGUEL/KEY_HANGEUL) the first one wins, which is
the name the kernel header lists as canonical.

  python3 tools/gen-keycodes.py [/usr/include/linux/input-event-codes.h]
"""
import re
import sys
from pathlib import Path

header = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/include/linux/input-event-codes.h")
names: dict[int, str] = {}
for match in re.finditer(r"^#define\s+((?:KEY|BTN)_[A-Z0-9_]+)\s+(0x[0-9a-fA-F]+|\d+)\b", header.read_text(), re.M):
    name, raw = match.groups()
    if name in ("KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING"):
        continue
    names.setdefault(int(raw, 0), name)

out = Path(__file__).resolve().parents[1] / "src/keycodes.rs"
lines = [
    "// Generated by tools/gen-keycodes.py from linux/input-event-codes.h. Do not edit.",
    "",
    "/// Linux EV_KEY codes and their header names, sorted by code.",
    "pub const NAMES: &[(u16, &str)] = &[",
]
lines += [f'    ({code}, "{name}"),' for code, name in sorted(names.items())]
lines += ["];", "", "pub fn name(code: u16) -> Option<&'static str> {",
          "    NAMES.binary_search_by_key(&code, |&(c, _)| c).ok().map(|i| NAMES[i].1)",
          "}", "", "pub fn code(name: &str) -> Option<u16> {",
          "    NAMES.iter().find(|&&(_, n)| n == name).map(|&(c, _)| c)",
          "}", ""]
out.write_text("\n".join(lines))
print(f"{out}: {len(names)} codes")
