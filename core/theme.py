def render_kitty(data: dict) -> str:
    c = derived(data)
    ansi = [
        c["tetsu"],
        c["vermillion"],
        c["positive"],
        c["warning"],
        c["indigo"],
        c["violet"],
        c["link"],
        c["washi"],
        c["muted"],
        c["accent_soft"],
        mix(c["positive"], c["washi"], 0.28),
        mix(c["warning"], c["washi"], 0.28),
        mix(c["indigo"], c["washi"], 0.48),
        mix(c["violet"], c["washi"], 0.34),
        mix(c["link"], c["washi"], 0.38),
        c["bright"],
    ]
    lines = [
        "# Generated by Cortetsu from ui.toml. Do not edit by hand.",
        f"foreground {c['washi']}",
        f"background {c['sumi']}",
        f"selection_foreground {c['washi']}",
        f"selection_background {c['indigo']}",
        f"cursor {c['vermillion']}",
        f"cursor_text_color {c['sumi']}",
        f"url_color {c['link']}",
        f"active_tab_foreground {c['washi']}",
        f"active_tab_background {c['indigo']}",
        f"inactive_tab_foreground {c['muted']}",
        f"inactive_tab_background {c['tetsu']}",
        f"tab_bar_background {c['sumi']}",
    ]
    lines.extend(f"color{index} {value}" for index, value in enumerate(ansi))
    return "\n".join(lines) + "\n"


