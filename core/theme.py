HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
THEME_KEYS = ("enableTerm", "enableHypr", "enableGtk", "enableQt")
WALL_UTILITY_REFS = {
    "surface_radius": ("shape", "radius_surface"),
    "panel_motion": ("motion", "panel_ms"),
    "orbit_motion": ("motion", "standard_ms"),
    "crossfade_motion": ("motion", "standard_ms"),
    "orbit_top_gap": ("spacing", "section"),
    "orbit_bottom_gap": ("spacing", "section"),
    "footer_gap": ("spacing", "compact"),
    "category_gap": ("spacing", "compact"),
}


def repo_root(value: str | None) -> Path:
    if value:
        return Path(value).expanduser().resolve()
    return Path(__file__).resolve().parents[1]


def resolve_wall_utility(data: dict) -> dict[str, int]:
    config = data.get("wall_utility")
    if not isinstance(config, dict):
        raise ValueError("missing [wall_utility] section")
    resolved: dict[str, int] = {}
    for name, (section, key) in WALL_UTILITY_REFS.items():
        reference = config.get(name)
        expected = f"{section}.{key}"
        if reference != expected:
            raise ValueError(f"invalid wall_utility.{name}: expected {expected!r}")
        value = data.get(section, {}).get(key)
        if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
            raise ValueError(f"invalid wall_utility resolved value: {expected}")
        resolved[name] = value
    return resolved


def load_ui(repo: Path) -> dict:
    path = repo / "dotfiles/home/.config/cortetsu/ui.toml"
    with path.open("rb") as handle:
        data = tomllib.load(handle)
    if data.get("schema") != 1:
        raise ValueError("ui.toml schema must be 1")
    palette = data.get("palette", {})
    for name in ("sumi", "tetsu", "washi", "indigo", "vermillion", "muted"):
        value = palette.get(name)
        if not isinstance(value, str) or not HEX.fullmatch(value):
            raise ValueError(f"invalid palette.{name}: {value!r}")
    semantic = palette.get("semantic", {})
    for name in ("surface_high", "primary_container", "secondary", "secondary_container", "outline_variant", "scrim"):
        value = semantic.get(name)
        if not isinstance(value, str) or not HEX.fullmatch(value):
            raise ValueError(f"invalid palette.semantic.{name}: {value!r}")
    motion = data.get("motion", {})
    for name in ("instant_ms", "fast_ms", "standard_ms", "deliberate_ms"):
        if not isinstance(motion.get(name), int) or motion[name] <= 0:
            raise ValueError(f"invalid motion.{name}")
    if not isinstance(motion.get("hover_scale"), (int, float)) or motion["hover_scale"] <= 1:
        raise ValueError("invalid motion.hover_scale")
    resolve_wall_utility(data)
    return data


def rgb(value: str) -> tuple[int, int, int]:
    return tuple(int(value[index : index + 2], 16) for index in (1, 3, 5))  # type: ignore[return-value]


def hex_colour(value: tuple[int, int, int]) -> str:
    return "#" + "".join(f"{max(0, min(255, channel)):02X}" for channel in value)


def mix(a: str, b: str, amount: float) -> str:
    ar, ag, ab = rgb(a)
    br, bg, bb = rgb(b)
    return hex_colour(
        (
            round(ar + (br - ar) * amount),
            round(ag + (bg - ag) * amount),
            round(ab + (bb - ab) * amount),
        )
    )


def rgb_csv(value: str) -> str:
    return ",".join(str(channel) for channel in rgb(value))


def derived(data: dict) -> dict[str, str]:
    p = data["palette"]
    return {
        **p,
        "surface_alt": mix(p["sumi"], p["tetsu"], 0.55),
        "accent_soft": mix(p["vermillion"], p["washi"], 0.24),
        "link": mix(p["indigo"], p["washi"], 0.38),
        "positive": mix(p["indigo"], p["washi"], 0.56),
        "warning": mix(p["vermillion"], p["washi"], 0.48),
        "bright": mix(p["washi"], "#FFFFFF", 0.58),
        "dim": mix(p["muted"], p["sumi"], 0.34),
        "violet": mix(p["indigo"], p["vermillion"], 0.46),
    }


