def colour_section(name: str, bg: str, alt: str, fg: str, c: dict[str, str]) -> str:
    fields = {
        "BackgroundAlternate": alt,
        "BackgroundNormal": bg,
        "DecorationFocus": c["vermillion"],
        "DecorationHover": c["accent_soft"],
        "ForegroundActive": c["accent_soft"],
        "ForegroundInactive": c["muted"],
        "ForegroundLink": c["link"],
        "ForegroundNegative": c["vermillion"],
        "ForegroundNeutral": c["warning"],
        "ForegroundNormal": fg,
        "ForegroundPositive": c["positive"],
        "ForegroundVisited": c["violet"],
    }
    return "[" + name + "]\n" + "\n".join(f"{key}={rgb_csv(value)}" for key, value in fields.items()) + "\n"


