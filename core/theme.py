def outputs(repo: Path, data: dict) -> dict[Path, str]:
    generated = repo / "dotfiles/generated/theme/home/.config"
    return {
        repo / "cortetsu/modules/CortetsuDesign.js": render_design(data),
        generated / "kitty/cortetsu-theme.conf": render_kitty(data),
        generated / "gtk-3.0/cortetsu-colors.css": render_gtk(data),
        generated / "gtk-4.0/cortetsu-colors.css": render_gtk(data),
        generated / "kdeglobals": render_kde(data),
    }


def compile_theme(repo: Path) -> int:
    data = load_ui(repo)
    for path, content in outputs(repo, data).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"GENERATED {path.relative_to(repo)}")
    return 0


def check_theme(repo: Path) -> int:
    data = load_ui(repo)
    stale: list[Path] = []
    for path, expected in outputs(repo, data).items():
        if not path.is_file() or path.read_text(encoding="utf-8") != expected:
            stale.append(path)
    if stale:
        for path in stale:
            print(f"STALE {path.relative_to(repo)}", file=sys.stderr)
        print("ERROR: run `cortetsu theme compile` and commit the generated outputs", file=sys.stderr)
        return 1
    print("PASS: Cortetsu native theme outputs match ui.toml")
    return 0


def adopt_theme_ownership() -> int:
    home = Path.home()
    config_home = Path(os.environ.get("XDG_CONFIG_HOME", home / ".config"))
    data_home = Path(os.environ.get("XDG_DATA_HOME", home / ".local/share"))
    cli = config_home / "caelestia/cli.json"
    if not cli.is_file():
        print(f"Cortetsu theme ownership: no Caelestia CLI config at {cli}; nothing to disable")
        return 0
    try:
        payload = json.loads(cli.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"cannot read {cli}: {exc}") from exc
    if not isinstance(payload, dict):
        raise RuntimeError(f"{cli} does not contain a JSON object")
    theme = payload.setdefault("theme", {})
    if not isinstance(theme, dict):
        raise RuntimeError(f"theme in {cli} is not a JSON object")
    changed = [key for key in THEME_KEYS if theme.get(key) is not False]
    if not changed:
        print("Cortetsu theme ownership: already native for terminal/Hyprland/GTK/Qt")
        return 0

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = data_home / "cortetsu/migrations" / stamp / "theme-ownership" / "cli.json"
    backup.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(cli, backup)
    for key in THEME_KEYS:
        theme[key] = False
    temp = cli.with_name(cli.name + f".tmp.{os.getpid()}")
    temp.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    os.replace(temp, cli)
    print("Cortetsu theme ownership: disabled Caelestia mutations for terminal/Hyprland/GTK/Qt")
    print(f"BACKUP theme-ownership={backup}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Compile and own the Cortetsu desktop theme")
    parser.add_argument("action", choices=("compile", "check", "adopt"), nargs="?", default="check")
    parser.add_argument("--repo")
    args = parser.parse_args()
    repo = repo_root(args.repo)
    try:
        if args.action == "compile":
            return compile_theme(repo)
        if args.action == "adopt":
            return adopt_theme_ownership()
        return check_theme(repo)
    except (OSError, ValueError, RuntimeError, tomllib.TOMLDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
