import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const policy = vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('../../cortetsu/services/BluetoothPolicy.js', import.meta.url), 'utf8'), policy);
const device = {connected: false, paired: false, bonded: true, pairing: true, trusted: false, blocked: false};
assert.equal(policy.completion('disconnect', device, false, [device]), true);
device.connected = true;
assert.equal(policy.completion('disconnect', device, false, [device]), false);
assert.equal(policy.completion('pair', device, false, [device]), false);
device.paired = true;
assert.equal(policy.completion('pair', device, false, [device]), true);
assert.equal(policy.completion('forget', device, false, [device]), false);
assert.equal(policy.completion('forget', device, false, []), true);
device.paired = false; device.bonded = false;
assert.equal(policy.completion('forget', device, false, [device]), false);
assert.equal(policy.completion('disconnect', device, false, []), 'removed');
assert.equal(policy.completion('disconnect', null, false, [device]), 'removed');
assert.equal(policy.completion('cancel-pair', device, false, [device]), false);
device.pairing = false;
assert.equal(policy.completion('cancel-pair', device, false, [device]), true);
assert.equal(policy.contains([device], device), true);
assert.equal(policy.contains([device], null), false);
assert.equal(policy.completion('trusted', device, true, [device]), false);
device.trusted = true;
assert.equal(policy.completion('trusted', device, true, [device]), true);
console.log('Bluetooth lifecycle policy: 16 checks passed');
